"""Rebuild the committed sparse AArch64 word image; no tools needed at run time."""
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
source = HERE / 'arm_split_timing.S'
with tempfile.TemporaryDirectory(prefix='split-s2-assemble-') as tmp:
    tmp = Path(tmp)
    subprocess.run(['aarch64-linux-gnu-gcc', '-nostdlib', '-static',
                    '-Wl,--build-id=none,-Ttext=0,-e,_start', '-o', str(tmp / 'guest.elf'),
                    str(source)], check=True)
    subprocess.run(['aarch64-linux-gnu-objcopy', '-O', 'binary', '-j', '.text',
                    str(tmp / 'guest.elf'), str(tmp / 'guest.bin')], check=True)
    payload = (tmp / 'guest.bin').read_bytes()
words = struct.unpack(f'<{len(payload) // 4}I', payload)
text = '# Generated by build_arm_split_timing.py; SPDX-License-Identifier: BSD-3-Clause\n'
text += f'SOURCE_SHA256 = {hashlib.sha256(source.read_bytes()).hexdigest()!r}\n'
text += f'SIZE = {len(payload)}\nWORDS = {{\n'
text += ''.join(f'    0x{i*4:04x}: 0x{word:08x},\n' for i, word in enumerate(words) if word)
text += '}\n'
(HERE / 'arm_split_timing_image.py').write_text(text)
print(f'Generated {len(payload)} bytes, {sum(bool(w) for w in words)} nonzero words')
